from unittest.mock import patch

from django.test import SimpleTestCase, override_settings
from django.urls import reverse


class GoogleOAuthLoginTests(SimpleTestCase):
    @override_settings(
        AUTHENTICATION_BACKENDS=[
            'django.contrib.auth.backends.ModelBackend',
            'account.authentication.EmailAuthBackend',
            'social_core.backends.google.GoogleOAuth2',
        ],
        SESSION_ENGINE='django.contrib.sessions.backends.signed_cookies',
        SOCIAL_AUTH_GOOGLE_OAUTH2_KEY='test-client-id',
        SOCIAL_AUTH_GOOGLE_OAUTH2_SECRET='test-client-secret',
    )
    @patch('social_django.storage.DjangoNonceMixin.use', return_value=True)
    def test_login_form_posts_and_starts_google_oauth(self, _nonce_mock):
        begin_url = reverse('social:begin', args=['google-oauth2'])
        login_response = self.client.get(reverse('login'))

        self.assertContains(login_response, f'<form method="post" action="{begin_url}">', html=False)
        self.assertContains(login_response, 'name="csrfmiddlewaretoken"')

        oauth_response = self.client.post(begin_url)

        self.assertEqual(oauth_response.status_code, 302)
        self.assertIn('accounts.google.com', oauth_response['Location'])

